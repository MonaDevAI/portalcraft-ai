        function queryTerms(value: string): string[] {
          return (value.toLowerCase().match(/[a-z0-9]+/g) || [])
            .filter(term => term.length > 1 && !QUERY_STOP_WORDS.has(term));
        }

        function queryScore(
          terms: readonly string[],
          query: PortalCraftAssistantQuery
        ): number {
          const prompt = query.prompt.toLowerCase();
          const identity = `${query.id} ${query.operationId}`.toLowerCase();
          return terms.reduce((score, term) => {
            if (prompt.includes(term)) return score + 3;
            if (identity.includes(term)) return score + 1;
            return score;
          }, 0);
        }

        export function findPortalCraftAssistantQuery(
          question: string
        ): PortalCraftAssistantQuery | undefined {
          const terms = queryTerms(question);
          if (terms.length === 0) return undefined;
          const best = portalCraftAssistantQueries
            .map(query => ({ query, score: queryScore(terms, query) }))
            .filter(item => item.score > 0)
            .sort((left, right) => right.score - left.score)[0];
          return best && best.score >= Math.min(4, terms.length * 2)
            ? best.query
            : undefined;
        }

        function parseQueryParameters(
          query: PortalCraftAssistantQuery,
          json: string | undefined
        ): Readonly<Record<string, unknown>> {
          if (!json) {
            if (query.parameters.length > 0) {
              throw new Error(`Missing query parameters: ${query.parameters.join(", ")}.`);
            }
            return {};
          }
          if (json.length > 4000) {
            throw new Error("Query parameters exceed the 4000-character limit.");
          }
          let parsed: unknown;
          try {
            parsed = JSON.parse(json);
          } catch {
            throw new Error("Query parameters must be a valid JSON object.");
          }
          if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
            throw new Error("Query parameters must be a JSON object.");
          }
          const parameters = parsed as Record<string, unknown>;
          const names = Object.keys(parameters);
          if (!names.every(name => SAFE_PARAMETER_NAME.test(name))) {
            throw new Error("Query parameters contain an invalid name.");
          }
          const allowed = new Set(query.parameters);
          const unsupported = names.filter(name => !allowed.has(name));
          if (unsupported.length > 0) {
            throw new Error(`Unsupported query parameters: ${unsupported.join(", ")}.`);
          }
          const missing = query.parameters.filter(
            name => !Object.prototype.hasOwnProperty.call(parameters, name)
          );
          if (missing.length > 0) {
            throw new Error(`Missing query parameters: ${missing.join(", ")}.`);
          }
          return parameters;
        }

        export function parsePortalCraftQueryCommand(
          input: string
        ): PortalCraftParsedQueryCommand | undefined {
          const match = input.trim().match(portalCraftQueryCommandPattern);
          if (!match) return undefined;
          const query = portalCraftAssistantQueries.find(candidate => candidate.id === match[1]);
          if (!query) {
            throw new Error(`Unknown read-only portal query "${match[1]}".`);
          }
          return {
            query,
            parameters: parseQueryParameters(query, match[2]),
          };
        }

        export function buildPortalCraftQueryCommand(
          queryId: string,
          parameters: Readonly<Record<string, unknown>> = {}
        ): string {
          const json = Object.keys(parameters).length > 0
            ? ` with ${JSON.stringify(parameters)}`
            : "";
          const command = `run portal query ${queryId}${json}`;
          parsePortalCraftQueryCommand(command);
          return command;
        }

        export async function executePortalCraftQueryCommand(
          input: string,
          executors: PortalCraftQueryExecutors
        ): Promise<string | undefined> {
          const parsed = parsePortalCraftQueryCommand(input);
          if (!parsed) return undefined;
          const executor = executors[parsed.query.operationId];
          if (!executor) {
            throw new Error(
              `No authorized executor is registered for "${parsed.query.operationId}".`
            );
          }
          return executor(parsed.parameters, parsed.query);
        }

        function isSafeResultActionUrl(url: string): boolean {
          return (url.startsWith("/") && !url.startsWith("//")) ||
            url.startsWith("https://");
        }

        export function formatPortalCraftQueryResult(
          result: PortalCraftQueryResult
        ): string {
          const title = result.title.trim();
          if (!title) throw new Error("A query result title is required.");
          const lines = [`**${title}**`];
          if (result.summary?.trim()) lines.push(result.summary.trim());
          const fields = (result.fields || []).filter(
            field => field.value !== null &&
              field.value !== undefined &&
              String(field.value).trim().length > 0
          );
          if (fields.length > 0) {
            lines.push("");
            fields.forEach(field => {
              lines.push(`**${field.label}:** ${String(field.value)}`);
            });
          }
          (result.sections || []).forEach(section => {
            if (!section.title.trim() || !section.content.trim()) return;
            lines.push("", `**${section.title.trim()}**`, section.content.trim());
          });
          const actions = (result.actions || []).filter(action => {
            if (!action.label.trim() || !isSafeResultActionUrl(action.url)) {
              throw new Error("Query result actions require a label and a safe portal or HTTPS URL.");
            }
            return true;
          });
          if (actions.length > 0) {
            lines.push("", actions.map(
              action => `[${action.label.trim()}](${action.url})`
            ).join(" · "));
          }
          return lines.join("\n");
        }

        function escapePortalCraftRegex(value: string): string {
          return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
        }

        export const portalCraftLookupClarificationPatterns: readonly RegExp[] = (() => {
          const aliases = portalCraftAssistantRequirements.lookupKeys
            .flatMap(key => key.aliases)
            .filter(Boolean)
            .sort((left, right) => right.length - left.length)
            .map(escapePortalCraftRegex);
          if (aliases.length === 0 ||
              portalCraftAssistantRequirements.businessEntities.length === 0) {
            return [];
          }
          const lookup = `(?:${aliases.join("|")})`;
          return [new RegExp(
            `^(?:can\\s+you\\s+|i\\s+want\\s+to\\s+)?` +
            `(?:find|search|show|fetch|look\\s*up)(?:\\s+me)?(?:\\s+(?:a|the|by))?` +
            `\\s+${lookup}(?:\\s+or\\s+${lookup})*[?.]*$`,
            "i"
          )];
        })();

        export function answerPortalCraftLookupClarification(
          input: string
        ): string | undefined {
          const { lookupKeys, businessEntities } = portalCraftAssistantRequirements;
          if (!portalCraftLookupClarificationPatterns.some(
            pattern => pattern.test(input.trim())
          )) return undefined;

          const lines = [
            `**Find a request in ${portalCraftAssistantRequirements.assistantName}**`,
            "Which identifier do you have?",
            ...lookupKeys.map(key =>
              `- **${key.label}**${key.example ? ` — for example \`${key.example}\`` : ""}`
            ),
            "",
            "Which business entity should I search?",
          ];
          const groups = Array.from(new Set(businessEntities.map(entity => entity.group)));
          groups.forEach(group => {
            const labels = businessEntities
              .filter(entity => entity.group === group)
              .map(entity => entity.label);
            lines.push(`- **${group}:** ${labels.join(", ")}`);
          });
          lines.push(
            "",
            "After you provide the identifier and entity, I’ll return the matching request with a link that opens it highlighted in the portal."
          );
          return lines.join("\n");
        }

        export function buildPortalCraftRequestAction(
          entityId: string,
          requestId: string
        ): { label: string; url: string } {
          const entity = portalCraftAssistantRequirements.businessEntities.find(
            candidate => candidate.id.toLowerCase() === entityId.toLowerCase()
          );
          if (!entity) throw new Error(`Unknown portal business entity "${entityId}".`);
          const normalizedRequestId = requestId.trim();
          if (!normalizedRequestId) throw new Error("A request ID is required.");
          const parameters: Record<string, string> = {
            requestId: normalizedRequestId,
            highlightRequest: normalizedRequestId,
            ...entity.routeParameters,
          };
          const query = Object.entries(parameters)
            .map(([key, value]) =>
              `${encodeURIComponent(key)}=${encodeURIComponent(value)}`
            )
            .join("&");
          return {
            label: `Open highlighted ${entity.requestActionLabel || entity.label} request`,
            url: `${entity.requestRoute}?${query}`,
          };
        }

        export const portalCraftConversationPatterns = [
