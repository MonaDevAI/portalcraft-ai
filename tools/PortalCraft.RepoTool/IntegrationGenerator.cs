        export function answerPortalCraftConversation(
          input: string,
          assistantName = "Portal Assistant"
        ): string | undefined {
          const normalized = input.trim();
          if (portalCraftConversationPatterns.slice(0, 3).some(pattern => pattern.test(normalized))) {
            const examples = portalCraftCapabilityExamples();
            return [
              `Hi! I'm ${assistantName}.`,
              "I can run verified read-only portal queries and answer from reviewed help documents.",
              ...(examples.length > 0 ? ["", "Try asking:", ...examples] : []),
            ].join("\n");
          }
          if (portalCraftConversationPatterns[3].test(normalized)) {
            return "You're welcome. Ask another portal or reviewed help-document question whenever you're ready.";
          }
          return undefined;
        }

        function isSafeParameterValue(value: string): boolean {
          return value.length > 0 &&
            value.length <= 200 &&
            !Array.from(value).some(character => {
              const code = character.charCodeAt(0);
              return code < 32 || code === 127;
            });
        }

        export function findPortalCraftAssistantView(
          requiredTags: readonly string[]
        ): string | undefined {
          const normalizedTags = requiredTags
            .map(tag => tag.trim().toLowerCase())
            .filter(Boolean);
          return portalCraftAssistantViews
            .filter(view => normalizedTags.every(
              tag => (view.tags as readonly string[]).includes(tag)
            ))
            .sort((left, right) => left.path.length - right.path.length)[0]?.path;
        }

        export function buildPortalCraftAssistantRoute(
          requiredTags: readonly string[],
          parameters: Readonly<Record<string, string>>
        ): string | undefined {
          const path = findPortalCraftAssistantView(requiredTags);
          if (!path || !path.startsWith("/") || path.startsWith("//")) return undefined;
          const entries: Array<[string, string]> = Object.entries(parameters)
            .map(([name, value]) => [name, value.trim()]);
          if (!entries.every(
            ([name, value]) => SAFE_PARAMETER_NAME.test(name) && isSafeParameterValue(value)
          )) return undefined;
          const suffix = new URLSearchParams(entries).toString();
          return suffix ? `${path}?${suffix}` : path;
        }

        function helpTerms(value: string): string[] {
          return (value.toLowerCase().match(/[a-z0-9]+/g) || [])
            .filter(term => term.length > 2 && !HELP_STOP_WORDS.has(term));
        }

        function helpTopicScore(
          terms: readonly string[],
          topic: PortalCraftHelpTopic
        ): number {
          if (topic.title.trim().toLowerCase() === topic.documentTitle.trim().toLowerCase()) {
            return 0;
          }
          const title = topic.title.toLowerCase();
          const summary = topic.summary.toLowerCase();
          return terms.reduce((score, term) => {
            if (title.includes(term)) return score + 3;
            if (summary.includes(term)) return score + 1;
            return score;
          }, 0);
        }

        export function findPortalCraftHelpTopic(
          topicIdOrQuestion: string
        ): PortalCraftHelpTopic | undefined {
          const normalized = topicIdOrQuestion.trim().toLowerCase();
          if (SAFE_HELP_TOPIC_ID.test(normalized)) {
            const exact = portalCraftHelpTopics.find(topic => topic.id === normalized);
            if (exact) return exact;
          }
          const terms = helpTerms(topicIdOrQuestion);
          if (terms.length === 0) return undefined;
          return portalCraftHelpTopics
            .map(topic => ({ topic, score: helpTopicScore(terms, topic) }))
            .filter(item => item.score >= MIN_HELP_TOPIC_SCORE)
            .sort((left, right) => right.score - left.score)[0]?.topic;
        }

        export function answerPortalCraftHelpTopic(
          topicIdOrQuestion: string
        ): string {
          const topic = findPortalCraftHelpTopic(topicIdOrQuestion);
          if (!topic) {
            return "No verified help-document topic matched that question.";
          }
          const citation = topic.sourceUrl
            ? `[${topic.sourceTitle}](${topic.sourceUrl})`
            : `${topic.sourceTitle} (${topic.repositoryPath})`;
          return [
            `**${topic.documentTitle} — ${topic.title}**`,
            topic.summary,
            "",
            `Source: ${citation}`,
          ].join("\n");
        }

        export function answerPortalCraftHelpQuestion(
          input: string
        ): string | undefined {
          const match = portalCraftHelpQuestionPatterns
            .map(pattern => input.trim().match(pattern))
            .find(candidate => candidate !== null);
          if (!match) return undefined;
          const topic = findPortalCraftHelpTopic(match[1] || match[0]);
          return topic ? answerPortalCraftHelpTopic(topic.id) : undefined;
        }
        """;
    }

    private static PortalCraftAssistantConfiguration? ValidateAssistantConfiguration(
        PortalCraftAssistantConfiguration? configuration)
    {
        if (configuration is null)
        {
            return null;
        }
        if (string.IsNullOrWhiteSpace(configuration.AssistantName))
        {
            throw new InvalidOperationException("Assistant configuration requires assistantName.");
        }
        if (configuration.AssistantIcon is not ("portalcraft" or "host-default"))
        {
            throw new InvalidOperationException(
                "Assistant configuration assistantIcon must be portalcraft or host-default.");
        }
        if (configuration.LookupKeys.Select(key => key.Id).Distinct(StringComparer.OrdinalIgnoreCase).Count()
            != configuration.LookupKeys.Count)
        {
            throw new InvalidOperationException("Assistant lookup key IDs must be unique.");
        }
        foreach (var key in configuration.LookupKeys)
        {
            if (string.IsNullOrWhiteSpace(key.Id)
                || string.IsNullOrWhiteSpace(key.Label)
                || key.Aliases.Count == 0
                || key.Aliases.Any(string.IsNullOrWhiteSpace))
            {
                throw new InvalidOperationException(
                    "Each assistant lookup key requires an id, label, and at least one alias.");
            }
        }
        if (configuration.BusinessEntities
            .Select(entity => entity.Id)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .Count() != configuration.BusinessEntities.Count)
        {
            throw new InvalidOperationException("Assistant business entity IDs must be unique.");
        }
        foreach (var entity in configuration.BusinessEntities)
        {
            if (string.IsNullOrWhiteSpace(entity.Id)
                || string.IsNullOrWhiteSpace(entity.Label)
                || string.IsNullOrWhiteSpace(entity.Group)
                || entity.Aliases.Count == 0
                || entity.Aliases.Any(string.IsNullOrWhiteSpace)
                || !entity.RequestRoute.StartsWith("/", StringComparison.Ordinal)
                || entity.RequestRoute.StartsWith("//", StringComparison.Ordinal))
            {
                throw new InvalidOperationException(
                    "Each assistant business entity requires an id, label, group, aliases, and a safe portal requestRoute.");
            }
        }
        return configuration;
    }

    private static string BuildHelpSampleQuestion(string title)
    {
        var subject = Regex.Replace(title, @"^\d+(?:\.\d+)*\s*", "").Trim();
        return $"Explain {(subject.Length > 0 ? subject : "this help topic")}";
    }

    private static IReadOnlyList<object> BuildHelpTopics(
        IReadOnlyList<RepositoryDocument> documents)
    {
        var topics = new List<object>();
        var usedIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var document in documents)
        {
            var sections = document.Sections.Count > 0
                ? document.Sections
                : [new RepositoryDocumentSection("Overview", document.Summary)];
            foreach (var section in sections)
            {
                var baseId = ToSlug($"{document.Title}-{section.Title}");
                var id = baseId;
                var suffix = 2;
                while (!usedIds.Add(id))
                {
                    id = $"{baseId}-{suffix}";
                    suffix += 1;
                }
                topics.Add(new
                {
                    id,
                    section.Title,
                    documentTitle = document.Title,
                    section.Summary,
                    sourceTitle = document.SourceTitle ?? document.Title,
                    document.SourceUrl,
                    repositoryPath = document.Path
                });
            }
        }
        return topics;
    }

