    private static string Escape(string value) =>
        value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string NullableString(string? value) =>
        value is null ? "null" : $"\"{Escape(value)}\"";

    private static IReadOnlyList<string> GetRouteTags(string route) =>
        Words(route)
            .Select(word => word.ToLowerInvariant())
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToArray();

    private static string ToSlug(string value)
    {
        var words = Words(value)
            .SelectMany(word => System.Text.RegularExpressions.Regex
                .Matches(word.ToLowerInvariant(), "[a-z0-9]+")
                .Cast<System.Text.RegularExpressions.Match>()
                .Select(match => match.Value))
            .Where(word => word.Length > 0)
            .Take(18)
            .ToArray();
        var slug = string.Join("-", words);
        if (slug.Length == 0)
        {
            return "help-topic";
        }
        return slug.Length <= 150 ? slug : slug[..150].TrimEnd('-');
    }

    private static IEnumerable<string> Words(string value) =>
        System.Text.RegularExpressions.Regex
            .Replace(value, "([a-z0-9])([A-Z])", "$1 $2")
            .Split(['/', '-', '_', ' '], StringSplitOptions.RemoveEmptyEntries);
}
